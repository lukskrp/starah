"""Generates org.starah.Session.svg (next to this script; run it after editing): an old-fashioned brass balance holding three
bricks in each pan, in front of a faint, serrated Tulsi leaf."""
import math

# ---- the leaf -------------------------------------------------------------
BASE, TIP = (46.0, 214.0), (222.0, 30.0)
AX = (TIP[0] - BASE[0], TIP[1] - BASE[1])
LEN = math.hypot(*AX)
UX, UY = AX[0] / LEN, AX[1] / LEN          # along the midrib
NX, NY = -UY, UX                           # across it


def at(t, off):
    """Point at fraction t along the (slightly curved) midrib, off across it."""
    bow = 10 * math.sin(math.pi * t)       # the midrib bows a little
    return (BASE[0] + UX * LEN * t + NX * (off + bow),
            BASE[1] + UY * LEN * t + NY * (off + bow))


def half_width(t):
    # Broad near the middle, rounded at the base, a long pointed tip.
    return 62 * (math.sin(math.pi * t ** 0.85) ** 0.9) * (1 - 0.18 * t)


def edge(side, n=220, teeth=11):
    pts = []
    for i in range(n + 1):
        t = i / n
        w = half_width(t)
        wave = 3.2 * math.sin(2.6 * math.pi * t + (0.8 if side > 0 else 2.1))
        # Serration: forward-leaning saw teeth, fading out at the base and the tip.
        phase = (t * teeth) % 1.0
        saw = (phase if phase < 0.75 else (1 - phase) * 3) * 4.0
        fade = min(1.0, max(0.0, (t - 0.12) / 0.15)) * min(1.0, (1 - t) / 0.12)
        pts.append(at(t, side * (w + wave + saw * fade)))
    return pts


def path_of(points, close=True):
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in points)
    return d + (" Z" if close else "")


left, right = edge(+1), edge(-1)
leaf = path_of(left + right[::-1])
midrib = path_of([at(t / 40, 0) for t in range(0, 39)], close=False)
veins = []
for t0 in (0.22, 0.36, 0.5, 0.63, 0.75):
    for side in (+1, -1):
        w = half_width(t0 + 0.08) * 0.78
        p0, p1, p2 = at(t0, 0), at(t0 + 0.05, side * w * 0.55), at(t0 + 0.1, side * w)
        veins.append(f"M{p0[0]:.1f} {p0[1]:.1f} Q{p1[0]:.1f} {p1[1]:.1f} {p2[0]:.1f} {p2[1]:.1f}")
stem0, stem1 = at(0, 0), (BASE[0] - 16, BASE[1] + 22)

# ---- the balance ----------------------------------------------------------
BRASS, DARK, LIGHT = "#c9a043", "#5e420f", "#f1d98f"


def pan(cx):
    top = 84  # where the strings hang from, under the beam's end
    rim = 154
    out = []
    # Three cords to the dish (left, back, right), from a small hook.
    for dx in (-34, 0, 34):
        out.append(f'<path d="M{cx} {top} L{cx + dx} {rim}" stroke="{DARK}" stroke-width="2.2" fill="none"/>')
    out.append(f'<circle cx="{cx}" cy="{top - 3}" r="4" fill="none" stroke="{DARK}" stroke-width="2.4"/>')
    # Bricks: two below, one on top, resting in the dish.
    for bx, by in ((cx - 23, 136), (cx + 1, 136), (cx - 11, 122)):
        out.append(f'<use href="#brick" x="{bx}" y="{by}"/>')
    # The dish: a shallow bowl and its rim.
    out.append(f'<path d="M{cx - 38} {rim} Q{cx} {rim + 28} {cx + 38} {rim} Z" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6" stroke-linejoin="round"/>')
    out.append(f'<ellipse cx="{cx}" cy="{rim}" rx="38" ry="4.5" fill="{LIGHT}" stroke="{DARK}" stroke-width="2.4"/>')
    return "\n    ".join(out)


# The column: a turned (baluster) post, symmetrical about x=128.
profile = [(60, 4), (70, 5), (78, 4), (96, 6), (112, 10), (124, 6), (140, 4.5), (176, 5),
           (188, 9), (198, 12), (206, 8)]
col_r = [(128 + w, y) for y, w in profile]
col_l = [(128 - w, y) for y, w in profile][::-1]
column = path_of(col_r + col_l)

svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">
  <title>Starah: agent privileges</title>
  <!-- An old brass balance, level, with three bricks in each pan, in front of a
       faint Tulsi leaf. Generated by make_icon.py. -->
  <defs>
    <g id="brick">
      <rect x="0" y="0" width="22" height="13" rx="2" fill="#c8623a" stroke="#6e2e18" stroke-width="2.4"/>
      <path d="M3.5 4 H18.5" stroke="#eea07e" stroke-width="1.8" stroke-linecap="round"/>
    </g>
  </defs>

  <!-- The leaf, light, as a shadow behind the balance. -->
  <g opacity="0.42">
    <path d="M{stem0[0]:.1f} {stem0[1]:.1f} Q{BASE[0] - 4:.1f} {BASE[1] + 14:.1f} {stem1[0]:.1f} {stem1[1]:.1f}" stroke="#2f9f93" stroke-width="5" stroke-linecap="round" fill="none"/>
    <path d="{leaf}" fill="#45bdb2" stroke="#2f9f93" stroke-width="2" stroke-linejoin="round"/>
    <path d="{midrib}" stroke="#e9fbf8" stroke-width="3.2" stroke-linecap="round" fill="none"/>
    <path d="{' '.join(veins)}" stroke="#e9fbf8" stroke-width="2" stroke-linecap="round" fill="none"/>
  </g>

  <g stroke-linejoin="round">
    <!-- Base: a stepped pedestal. -->
    <rect x="98" y="204" width="60" height="10" rx="3" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <rect x="84" y="213" width="88" height="11" rx="4" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <rect x="72" y="223" width="112" height="11" rx="5.5" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <!-- The turned column, and its finial above the beam. -->
    <path d="{column}" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <path d="M128 108 V190" stroke="{LIGHT}" stroke-width="2" stroke-linecap="round"/>
    <path d="M122 60 L128 40 L134 60 Z" fill="{BRASS}" stroke="{DARK}" stroke-width="2.4"/>
    <circle cx="128" cy="36" r="5.5" fill="{BRASS}" stroke="{DARK}" stroke-width="2.4"/>
    <!-- The beam: gently arched, with knobs at its ends, resting on the column. -->
    <path d="M30 76 Q128 56 226 76 L226 84 Q128 64 30 84 Z" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <circle cx="28" cy="80" r="6" fill="{BRASS}" stroke="{DARK}" stroke-width="2.4"/>
    <circle cx="228" cy="80" r="6" fill="{BRASS}" stroke="{DARK}" stroke-width="2.4"/>
    <rect x="119" y="60" width="18" height="16" rx="3" fill="{BRASS}" stroke="{DARK}" stroke-width="2.6"/>
    <!-- The pans. -->
    {pan(48)}
    {pan(208)}
  </g>
</svg>
"""
import pathlib
(pathlib.Path(__file__).parent / "org.starah.Session.svg").write_text(svg)
print(len(svg), "bytes")
