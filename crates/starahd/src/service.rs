pub const BUS_NAME: &str = "org.starah.Broker1";
pub const OBJECT_PATH: &str = "/org/starah/Broker1";

const ACTION_CONFIGURE: &str = "org.starah.configure";
const ACTION_DECIDE: &str = "org.starah.decide";
const ACTION_RUN: &str = "org.starah.run";

/// /etc/starah/config.json, generated by the NixOS module.
#[derive(Debug, Deserialize)]
pub struct DaemonConfig {
    #[serde(flatten)]
    pub policy: Config,
    /// Agent `x` runs as system user `<prefix>x`.
    #[serde(default = "default_prefix")]
    pub user_prefix: String,
    #[serde(default = "default_workspaces")]
    pub workspaces: String,
    /// The user polkitd runs `starah-polkit-check` as; only it (and root) may Check.
    #[serde(default = "default_polkit_user")]
    pub polkit_user: String,
    /// PATH inside agent processes.
    #[serde(default = "default_agent_path")]
    pub agent_path: String,
}

fn default_prefix() -> String {
    "starah-".into()
}
fn default_workspaces() -> String {
    "/var/lib/starah-agents".into()
}
fn default_polkit_user() -> String {
    "polkituser".into()
}
fn default_agent_path() -> String {
    "/run/current-system/sw/bin".into()
}

/// Who is calling, as the kernel tells the bus (SO_PEERCRED).
#[derive(Debug, Clone, PartialEq, Eq)]
enum Caller {
    Root,
    Polkit,
    Agent(String),
    Human(String),
}

impl Caller {
    fn name(&self) -> String {
        match self {
            Caller::Root => "root".into(),
            Caller::Polkit => "polkit".into(),
            Caller::Agent(a) => format!("agent {a}"),
            Caller::Human(u) => u.clone(),
        }
    }
}

pub struct Broker1 {
    cfg: Arc<DaemonConfig>,
    state_dir: PathBuf,
    broker: Arc<Mutex<Broker>>,
    /// Running agent units → the uid that started them (only it may Wait).
    units: Arc<Mutex<HashMap<String, u32>>>,
    next_unit: AtomicU64,
}

fn now() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// uid → user name, from /etc/passwd (NixOS keeps every account there).
fn user_name(uid: u32) -> Option<String> {
    let passwd = std::fs::read_to_string("/etc/passwd").ok()?;
    passwd.lines().find_map(|line| {
        let mut f = line.split(':');
        let name = f.next()?;
        f.next()?;
        (f.next()?.parse::<u32>().ok()? == uid).then(|| name.to_string())
    })
}

fn failed(msg: impl Into<String>) -> fdo::Error {
    fdo::Error::Failed(msg.into())
}

fn denied(msg: impl Into<String>) -> fdo::Error {
    fdo::Error::AccessDenied(msg.into())
}

impl Broker1 {
    async fn caller(&self, conn: &Connection, hdr: &Header<'_>) -> fdo::Result<(Caller, u32)> {
        let sender = hdr
            .sender()
            .ok_or_else(|| denied("message has no sender"))?;
        let dbus = fdo::DBusProxy::new(conn).await?;
        let uid = dbus.get_connection_unix_user(sender.clone().into()).await?;
        if uid == 0 {
            return Ok((Caller::Root, uid));
        }
        let name = user_name(uid).ok_or_else(|| denied(format!("unknown uid {uid}")))?;
        if name == self.cfg.polkit_user {
            return Ok((Caller::Polkit, uid));
        }
        if let Some(agent) = self.agent_of_user(&name) {
            return Ok((Caller::Agent(agent), uid));
        }
        Ok((Caller::Human(name), uid))
    }

    /// `starah-assistant` → `assistant`, for declared agents only. A user that merely
    /// has the prefix but is not declared is treated as an (unknown) agent too, so it
    /// can never act as a human.
    fn agent_of_user(&self, user: &str) -> Option<String> {
        user.strip_prefix(&self.cfg.user_prefix).map(str::to_string)
    }

    async fn require_human(
        &self,
        conn: &Connection,
        hdr: &Header<'_>,
        action: &str,
    ) -> fdo::Result<Caller> {
        let (caller, _) = self.caller(conn, hdr).await?;
        match &caller {
            Caller::Agent(a) => Err(denied(format!(
                "agent {a} may not do this; only a human can ({action})"
            ))),
            Caller::Polkit => Err(denied("not for polkit")),
            Caller::Root => Ok(caller),
            Caller::Human(_) => {
                let sender = hdr.sender().ok_or_else(|| denied("no sender"))?;
                if polkit::check(conn, sender.as_str(), action)
                    .await
                    .map_err(|e| failed(format!("polkit: {e}")))?
                {
                    Ok(caller)
                } else {
                    Err(denied(format!("not authorized for {action}")))
                }
            }
        }
    }

    fn audit(&self, event: &str, fields: serde_json::Value) {
        let mut entry = json!({ "time": now(), "event": event });
        if let (Some(e), Some(f)) = (entry.as_object_mut(), fields.as_object()) {
            for (k, v) in f {
                e.insert(k.clone(), v.clone());
            }
        }
        let line = entry.to_string();
        eprintln!("starah: {line}");
        let path = self.state_dir.join("audit.jsonl");
        if let Ok(mut f) = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(&path)
        {
            let _ = writeln!(f, "{line}");
        }
    }

    fn save_policy(&self, policy: &Policy) -> std::io::Result<()> {
        let path = self.state_dir.join("policy.json");
        let tmp = self.state_dir.join("policy.json.tmp");
        std::fs::write(&tmp, serde_json::to_vec_pretty(policy)?)?;
        std::fs::rename(tmp, path)
    }

    fn policy_json(&self, b: &Broker) -> String {
        let agents: Vec<_> = b
            .config
            .agents
            .iter()
            .map(|(name, spec)| {
                let level = b.level(name).unwrap_or(spec.level);
                json!({
                    "name": name,
                    "description": spec.description,
                    "user": format!("{}{}", self.cfg.user_prefix, name),
                    "level": level,
                    "level_name": level.name(),
                    "default_level": spec.level,
                    // People who let this agent use their whole home.
                    "home_access": b.policy.home_access.get(name).cloned().unwrap_or_default(),
                })
            })
            .collect();
        let levels: Vec<_> = Level::ALL
            .iter()
            .map(|l| json!({ "level": l, "name": l.name() }))
            .collect();
        json!({
            "configured": b.policy.configured,
            "configured_by": b.policy.configured_by,
            "configured_at": b.policy.configured_at,
            "agents": agents,
            "levels": levels,
        })
        .to_string()
    }

    async fn announce(emitter: &SignalEmitter<'_>, outcome: &Outcome, b: &Broker) {
        if let Outcome::Pending { id } = outcome {
            if let Some(r) = b.request(*id) {
                if r.created == now() || r.status == Status::Pending {
                    let _ = Broker1::request_added(
                        emitter,
                        *id,
                        &serde_json::to_string(r).unwrap_or_default(),
                    )
                    .await;
                }
            }
        }
    }
}

#[interface(name = "org.starah.Broker1")]
impl Broker1 {
    /// The agents, their levels and whether the human has confirmed them (JSON).
    async fn get_policy(&self) -> String {
        let b = self.broker.lock().await;
        self.policy_json(&b)
    }

    /// The human sets levels: JSON `{"agent": level, …}`. Marks the policy configured.
    async fn set_policy(
        &self,
        levels: &str,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<()> {
        let caller = self.require_human(conn, &hdr, ACTION_CONFIGURE).await?;
        let levels: BTreeMap<String, Level> =
            serde_json::from_str(levels).map_err(|e| failed(format!("invalid levels: {e}")))?;
        let mut b = self.broker.lock().await;
        b.set_levels(levels.clone(), &caller.name(), now())
            .map_err(|e| failed(e.to_string()))?;
        self.save_policy(&b.policy)
            .map_err(|e| failed(format!("cannot save the policy: {e}")))?;
        self.audit(
            "set-policy",
            json!({ "by": caller.name(), "levels": levels }),
        );
        Ok(())
    }

    /// Called by `starah-polkit-check` (as polkitd's user) for every polkit question
    /// about an agent. Never blocks on the human.
    async fn check(
        &self,
        action: &str,
        user: &str,
        detail: &str,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
        #[zbus(signal_emitter)] emitter: SignalEmitter<'_>,
    ) -> fdo::Result<(bool, String)> {
        let (caller, _) = self.caller(conn, &hdr).await?;
        if !matches!(caller, Caller::Root | Caller::Polkit) {
            return Err(denied("only polkit may ask Check"));
        }
        let Some(agent) = self.agent_of_user(user) else {
            return Ok((false, format!("{user} is not an agent")));
        };
        let detail = (!detail.is_empty()).then_some(detail);
        let mut b = self.broker.lock().await;
        let outcome = b.check(&agent, action, detail, now());
        self.audit(
            "check",
            json!({ "agent": agent, "action": action, "detail": detail, "result": outcome }),
        );
        Broker1::announce(&emitter, &outcome, &b).await;
        let message = match &outcome {
            Outcome::Allow { why } | Outcome::Deny { why } => why.clone(),
            Outcome::Pending { id } => format!("waiting for the human to approve request {id}"),
        };
        Ok((outcome.allowed(), message))
    }

    /// A cooperating agent describes a change before making it (JSON description:
    /// title, reason, changes, diff). Returns (request id, status, message): status is
    /// "approved", "rejected" or "pending"; for pending, wait for `Decided(id, …)`.
    async fn ask(
        &self,
        action: &str,
        description: &str,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
        #[zbus(signal_emitter)] emitter: SignalEmitter<'_>,
    ) -> fdo::Result<(u64, String, String)> {
        let (caller, _) = self.caller(conn, &hdr).await?;
        let Caller::Agent(agent) = caller else {
            return Err(denied("Ask is for agents"));
        };
        let description: Description = serde_json::from_str(description)
            .map_err(|e| failed(format!("invalid description: {e}")))?;
        let mut b = self.broker.lock().await;
        let outcome = b.ask(&agent, action, description.clone(), now());
        self.audit(
            "ask",
            json!({ "agent": agent, "action": action, "title": description.title,
                    "changes": description.changes, "result": outcome }),
        );
        Broker1::announce(&emitter, &outcome, &b).await;
        Ok(match outcome {
            Outcome::Allow { why } => (0, "approved".into(), why),
            Outcome::Deny { why } => (0, "rejected".into(), why),
            Outcome::Pending { id } => (
                id,
                "pending".into(),
                format!("waiting for the human to approve request {id}"),
            ),
        })
    }

    /// The status of one request ("pending", "approved", "rejected", "expired").
    /// Agents may only ask about their own requests.
    async fn status(
        &self,
        id: u64,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<String> {
        let (caller, _) = self.caller(conn, &hdr).await?;
        let b = self.broker.lock().await;
        let r = b
            .request(id)
            .ok_or_else(|| failed(format!("no request {id}")))?;
        if let Caller::Agent(a) = &caller {
            if &r.agent != a {
                return Err(denied("not your request"));
            }
        }
        Ok(serde_json::to_value(r.status)
            .ok()
            .and_then(|v| v.as_str().map(str::to_string))
            .unwrap_or_default())
    }

    /// Pending requests (JSON list), for the human's approval queue.
    async fn requests(
        &self,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<String> {
        let (caller, _) = self.caller(conn, &hdr).await?;
        if matches!(caller, Caller::Agent(_)) {
            return Err(denied("agents cannot list requests"));
        }
        let mut b = self.broker.lock().await;
        b.expire(now());
        Ok(serde_json::to_string(&b.pending()).unwrap_or_else(|_| "[]".into()))
    }

    /// The human approves or rejects a request; `minutes` (0 = default) is how long
    /// a polkit-kind approval lasts.
    async fn decide(
        &self,
        id: u64,
        approve: bool,
        minutes: u32,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
        #[zbus(signal_emitter)] emitter: SignalEmitter<'_>,
    ) -> fdo::Result<()> {
        let caller = self.require_human(conn, &hdr, ACTION_DECIDE).await?;
        let mut b = self.broker.lock().await;
        let minutes = (minutes > 0).then_some(minutes as u64);
        let req = b
            .decide(id, approve, minutes, &caller.name(), now())
            .map_err(|e| failed(e.to_string()))?;
        self.audit(
            "decide",
            json!({ "id": id, "agent": req.agent, "action": req.action,
                    "approved": approve, "by": caller.name() }),
        );
        let status = if approve { "approved" } else { "rejected" };
        let _ = Broker1::decided(&emitter, id, approve, status).await;
        Ok(())
    }

    /// Starts `argv` as agent `agent`, sandboxed, with the caller's stdio. Returns the
    /// unit name for `Wait`.
    #[allow(clippy::too_many_arguments)]
    async fn run(
        &self,
        agent: &str,
        argv: Vec<String>,
        stdin: zbus::zvariant::OwnedFd,
        stdout: zbus::zvariant::OwnedFd,
        stderr: zbus::zvariant::OwnedFd,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<String> {
        let caller = self.require_human(conn, &hdr, ACTION_RUN).await?;
        let (_, uid) = self.caller(conn, &hdr).await?;
        {
            let b = self.broker.lock().await;
            if !b.config.agents.contains_key(agent) {
                return Err(failed(format!("no agent named {agent:?}")));
            }
        }
        if argv.is_empty() || !argv[0].starts_with('/') {
            return Err(failed("the command must be an absolute path"));
        }
        let n = self.next_unit.fetch_add(1, Ordering::Relaxed);
        let unit = format!("starah-{agent}-{}-{n}.service", std::process::id());
        let user = format!("{}{agent}", self.cfg.user_prefix);
        let workspace = format!("{}/{agent}", self.cfg.workspaces);
        let (stdin, stdout, stderr): (OwnedFd, OwnedFd, OwnedFd) =
            (stdin.into(), stdout.into(), stderr.into());
        systemd::start(
            conn,
            &systemd::Launch {
                unit: &unit,
                agent,
                user: &user,
                workspace: &workspace,
                argv: &argv,
                path: &self.cfg.agent_path,
                stdin: &stdin,
                stdout: &stdout,
                stderr: &stderr,
            },
        )
        .await
        .map_err(|e| failed(format!("cannot start the agent: {e}")))?;
        self.units.lock().await.insert(unit.clone(), uid);
        self.audit(
            "run",
            json!({ "agent": agent, "argv": argv, "unit": unit, "by": caller.name() }),
        );
        Ok(unit)
    }

    /// The caller lets `agent` use their whole home in interactive sessions (their
    /// logins, SSH keys and other projects), or takes that back. Asks for the
    /// administrator password like changing a level.
    async fn set_home_access(
        &self,
        agent: &str,
        allow: bool,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<()> {
        let caller = self.require_human(conn, &hdr, ACTION_CONFIGURE).await?;
        let Caller::Human(person) = &caller else {
            return Err(denied("only a person can share their home"));
        };
        let mut b = self.broker.lock().await;
        b.set_home_access(agent, person, allow)
            .map_err(|e| failed(e.to_string()))?;
        self.save_policy(&b.policy)
            .map_err(|e| failed(format!("cannot save the policy: {e}")))?;
        self.audit(
            "home-access",
            json!({ "agent": agent, "person": person, "allow": allow }),
        );
        Ok(())
    }

    /// Starts `argv` as agent `agent` on the caller's terminal `tty` (a /dev/pts
    /// the caller opened), in the caller's folder `cwd`, with the allowed variables
    /// of `env`. The agent sees that folder (or, if the caller allowed it, their
    /// whole home) through an idmapped mount: it works on the files as its own,
    /// and they stay the caller's. Returns the unit name for `Wait`. The session
    /// ends when the agent exits or the caller goes away.
    #[allow(clippy::too_many_arguments)]
    async fn run_interactive(
        &self,
        agent: &str,
        argv: Vec<String>,
        cwd: &str,
        env: Vec<String>,
        tty: &str,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<String> {
        let caller = self.require_human(conn, &hdr, ACTION_RUN).await?;
        let (_, uid) = self.caller(conn, &hdr).await?;
        let spec = {
            let b = self.broker.lock().await;
            b.config
                .agents
                .get(agent)
                .cloned()
                .ok_or_else(|| failed(format!("no agent named {agent:?}")))?
        };
        if argv.is_empty() || !argv[0].starts_with('/') {
            return Err(failed("the command must be an absolute path"));
        }
        // The terminal must be one the caller opened.
        {
            use std::os::unix::fs::MetadataExt;
            let meta = std::fs::metadata(tty).map_err(|e| failed(format!("{tty}: {e}")))?;
            if !session::is_pts(tty) || meta.uid() != uid {
                return Err(denied(format!("{tty} is not your terminal")));
            }
        }
        let person = session::account_by_uid(uid).ok_or_else(|| denied("unknown caller"))?;
        let user = format!("{}{agent}", self.cfg.user_prefix);
        let workspace = format!("{}/{agent}", self.cfg.workspaces);
        let whole_home = self.broker.lock().await.home_access(agent, &person.name);

        let n = self.next_unit.fetch_add(1, Ordering::Relaxed);
        let stem = format!("starah-{agent}-{}-{n}", std::process::id());
        let unit = format!("{stem}.service");
        let staging = format!("{}/{stem}", session::SESSIONS);
        let agent_home = format!("{workspace}/home/{}", person.name);
        let mut helper = vec![
            "--prepare-session".to_string(),
            uid.to_string(),
            user.clone(),
            if whole_home { "home" } else { "project" }.to_string(),
            cwd.to_string(),
            staging.clone(),
            agent_home.clone(),
        ];
        helper.extend(
            spec.home_links
                .iter()
                .map(|(rel, target)| format!("{rel}={target}")),
        );
        let ok = systemd::run_root(conn, &format!("{stem}-prepare.service"), &helper)
            .await
            .map_err(|e| failed(format!("cannot prepare the session: {e}")))?;
        if !ok {
            let why = std::fs::read_to_string(format!("{staging}.error"))
                .unwrap_or_else(|_| "see the journal".into());
            let _ = systemd::run_root(
                conn,
                &format!("{stem}-end.service"),
                &["--end-session".into(), staging.clone()],
            )
            .await;
            return Err(failed(why.trim().to_string()));
        }
        // Where the agent sees the shared folder: where it really is.
        let shared = if whole_home {
            person.home.to_string_lossy().into_owned()
        } else {
            std::path::Path::new(cwd)
                .canonicalize()
                .map(|p| p.to_string_lossy().into_owned())
                .unwrap_or_else(|_| cwd.to_string())
        };
        let mut vars: Vec<String> = env
            .into_iter()
            .filter(|kv| {
                kv.split_once('=')
                    .is_some_and(|(k, _)| session::allowed_env(k))
            })
            .collect();
        vars.push(format!(
            "HOME={}",
            if whole_home {
                shared.clone()
            } else {
                agent_home.clone()
            }
        ));
        let started = systemd::start_interactive(
            conn,
            &systemd::Interactive {
                unit: &unit,
                agent,
                user: &user,
                workspace: &workspace,
                argv: &argv,
                path: &self.cfg.agent_path,
                tty,
                cwd,
                staging: &staging,
                shared: &shared,
                env: &vars,
            },
        )
        .await;
        if let Err(e) = started {
            let _ = systemd::run_root(
                conn,
                &format!("{stem}-end.service"),
                &["--end-session".into(), staging.clone()],
            )
            .await;
            return Err(failed(format!("cannot start the agent: {e}")));
        }
        self.units.lock().await.insert(unit.clone(), uid);
        self.audit(
            "run",
            json!({ "agent": agent, "argv": argv, "unit": unit, "by": caller.name(),
                    "interactive": true, "cwd": cwd, "whole_home": whole_home }),
        );
        // End the session when the agent exits, or stop it when the caller is gone.
        let sender = hdr.sender().map(|s| s.to_string()).unwrap_or_default();
        let (conn, unit_w, units) = (conn.clone(), unit.clone(), self.units.clone());
        tokio::spawn(async move {
            systemd::watch_session(&conn, &unit_w, &sender).await;
            let _ = systemd::run_root(
                &conn,
                &format!("{stem}-end.service"),
                &["--end-session".into(), staging],
            )
            .await;
            units.lock().await.remove(&unit_w);
        });
        Ok(unit)
    }

    /// Waits for an agent unit started by the caller; returns its exit status.
    async fn wait(
        &self,
        unit: &str,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<i32> {
        let (_, uid) = self.caller(conn, &hdr).await?;
        let owner = self.units.lock().await.get(unit).copied();
        if owner != Some(uid) && uid != 0 {
            return Err(denied("not your agent unit"));
        }
        let status = systemd::wait(conn, unit)
            .await
            .map_err(|e| failed(format!("waiting for {unit}: {e}")))?;
        self.units.lock().await.remove(unit);
        self.audit("exit", json!({ "unit": unit, "status": status }));
        Ok(status)
    }

    /// The last `limit` audit entries (JSON lines).
    async fn audit_log(
        &self,
        limit: u32,
        #[zbus(connection)] conn: &Connection,
        #[zbus(header)] hdr: Header<'_>,
    ) -> fdo::Result<String> {
        let (caller, _) = self.caller(conn, &hdr).await?;
        if matches!(caller, Caller::Agent(_)) {
            return Err(denied("agents cannot read the audit log"));
        }
        let text = std::fs::read_to_string(self.state_dir.join("audit.jsonl")).unwrap_or_default();
        let lines: Vec<&str> = text.lines().collect();
        let start = lines.len().saturating_sub(limit.max(1) as usize);
        Ok(lines[start..].join("\n"))
    }

    #[zbus(signal)]
    async fn request_added(emitter: &SignalEmitter<'_>, id: u64, request: &str)
        -> zbus::Result<()>;

    #[zbus(signal)]
    async fn decided(
        emitter: &SignalEmitter<'_>,
        id: u64,
        approved: bool,
        status: &str,
    ) -> zbus::Result<()>;
}

pub async fn run(config: &Path, state_dir: &Path) -> Result<(), String> {
    let text = std::fs::read_to_string(config)
        .map_err(|e| format!("cannot read {}: {e}", config.display()))?;
    let cfg: DaemonConfig =
        serde_json::from_str(&text).map_err(|e| format!("invalid {}: {e}", config.display()))?;
    std::fs::create_dir_all(state_dir)
        .map_err(|e| format!("cannot create {}: {e}", state_dir.display()))?;
    let policy: Policy = std::fs::read_to_string(state_dir.join("policy.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();
    let broker = Arc::new(Mutex::new(Broker::new(cfg.policy.clone(), policy)));
    let service = Broker1 {
        cfg: Arc::new(cfg),
        state_dir: state_dir.to_path_buf(),
        broker: broker.clone(),
        units: Arc::new(Mutex::new(HashMap::new())),
        next_unit: AtomicU64::new(1),
    };
    let conn = zbus::connection::Builder::system()
        .map_err(|e| e.to_string())?
        .serve_at(OBJECT_PATH, service)
        .map_err(|e| e.to_string())?
        .name(BUS_NAME)
        .map_err(|e| e.to_string())?
        .build()
        .await
        .map_err(|e| format!("cannot own {BUS_NAME} on the system bus: {e}"))?;
    eprintln!("starahd: serving {BUS_NAME}");

    // Expire old requests and tell waiting agents.
    let emitter = SignalEmitter::new(&conn, OBJECT_PATH)
        .map_err(|e| e.to_string())?
        .into_owned();
    loop {
        tokio::time::sleep(std::time::Duration::from_secs(30)).await;
        let expired = broker.lock().await.expire(now());
        for id in expired {
            let _ = Broker1::decided(&emitter, id, false, "expired").await;
        }
    }
}
